"""GameStatsFetcher -- one client for every esports title.

Players, ranks, matches, leaderboards and the professional circuit behind them,
normalised across 83 titles and 51 real game APIs.

    >>> import asyncio
    >>> from gamestatsfetcher import GameStatsClient
    >>> async def main():
    ...     async with GameStatsClient() as client:          # no key needed
    ...         ranks = await client.dota2.get_rank({"steam_id": "76561198054320440"})
    ...         return ranks[0].tier
    >>> asyncio.run(main())                                  # doctest: +SKIP
    'Immortal'

The package is async throughout. Every method on a title client is a coroutine,
and the client is an async context manager so the transport gets closed.

Two rules shape everything the API returns:

1. **Nothing is invented.** A field the upstream does not provide is ``None``,
   never a plausible default.
2. **Unsupported raises.** A title that cannot answer a question says so with
   :class:`UnsupportedCapabilityError`; it never returns an empty list that
   looks like a quiet week.
"""

