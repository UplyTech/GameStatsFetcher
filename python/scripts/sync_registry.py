#!/usr/bin/env python
"""Copy ``shared/registry/`` into the Python package's data directory.

The registry is generated by the TypeScript edition, which is where the title
list and the reconciliation logic live. This edition ships the result as package
data so a wheel is self-contained - a user pip-installing the package does not
have the repository.

    python scripts/sync_registry.py            # copy
    python scripts/sync_registry.py --check    # fail if out of date (CI)

``tests/test_registry_sync.py`` runs the check too, so a stale copy fails the
suite rather than shipping two editions that disagree about their own coverage.
"""

from __future__ import annotations

import sys
from pathlib import Path

#: The files that make up the registry. ``coverage.json`` is a convenience view
#: for documentation, not something the runtime reads, so it is not copied.
FILES = ("titles.json", "providers.json")

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent.parent / "shared" / "registry"
TARGET = HERE.parent / "src" / "gamestatsfetcher" / "data"


def main() -> int:
    check = "--check" in sys.argv

    if not SOURCE.is_dir():
        print(f"source not found: {SOURCE}", file=sys.stderr)
        print(
            "Run `npm run build && npm run registry` in ../typescript first.",
            file=sys.stderr,
        )
        return 1

    TARGET.mkdir(parents=True, exist_ok=True)
    stale: list[str] = []

    for name in FILES:
        source = SOURCE / name
        target = TARGET / name
        if not source.is_file():
            print(f"missing: shared/registry/{name}", file=sys.stderr)
            return 1

        # Compared as bytes: a whitespace-only difference is still a difference,
        # and the generator writes deterministically.
        wanted = source.read_bytes()
        current = target.read_bytes() if target.is_file() else b""

        if check:
            if wanted != current:
                stale.append(name)
            continue

        if wanted != current:
            target.write_bytes(wanted)
            print(f"updated src/gamestatsfetcher/data/{name}")
        else:
            print(f"unchanged src/gamestatsfetcher/data/{name}")

    if check:
        if stale:
            print(
                "\nout of date: " + ", ".join(stale),
                file=sys.stderr,
            )
            print(
                "Run `python scripts/sync_registry.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print("package data matches shared/registry.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
